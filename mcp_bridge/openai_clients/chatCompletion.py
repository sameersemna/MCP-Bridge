def _context_budget_exceeded(
    response: CreateChatCompletionResponse,
    max_context_tokens: int,
) -> bool:
    """Return True if the accumulated prompt context exceeds the budget."""
    usage = getattr(response, "usage", None)
    if usage is None:
        return False
    prompt_tokens = getattr(usage, "prompt_tokens", None)
    if not isinstance(prompt_tokens, int):
        return False
    return prompt_tokens > max_context_tokens


def _context_budget_nearly_exceeded(
    response: CreateChatCompletionResponse,
    max_context_tokens: int,
    threshold: float = 0.7,
) -> bool:
    """Return True if the accumulated prompt context is approaching the budget.

    Used to trigger proactive context compression before the hard limit is hit,
    so the tool loop can keep going instead of stopping early.
    """
    usage = getattr(response, "usage", None)
    if usage is None:
        return False
    prompt_tokens = getattr(usage, "prompt_tokens", None)
    if not isinstance(prompt_tokens, int):
        return False
    return prompt_tokens > (max_context_tokens * threshold)


def _compress_tool_context(
    request_messages: list[ChatCompletionRequestMessage],
    *,
    keep_recent: int = 6,
) -> bool:
    """Compress older tool messages into a single compact summary.

    Long research workflows accumulate many tool messages (search results,
    fetched pages) that bloat the prompt context. When the budget is nearly
    exceeded, this replaces the OLDEST tool messages with a single summarized
    ``role: "tool"`` message, freeing context so the loop can continue.

    Returns True if compression was performed, False otherwise.
    """
    if not request_messages:
        return False

    # Identify tool messages and their indices.
    tool_indices: list[int] = []
    for index, message in enumerate(request_messages):
        role = getattr(getattr(message, "root", message), "role", None)
        if role == "tool":
            tool_indices.append(index)

    if len(tool_indices) <= keep_recent:
        # Not enough tool messages to compress meaningfully.
        return False

    # Keep the most recent `keep_recent` tool messages; compress the older ones.
    compress_indices = tool_indices[:-keep_recent]
    keep_indices = set(tool_indices[-keep_recent:])

    tool_texts: list[str] = []
    for index in compress_indices:
        text = _extract_tool_message_text(request_messages[index])
        if text:
            tool_texts.append(text)

    if not tool_texts:
        return False

    summary = _summarize_tool_messages(tool_texts)
    if not summary:
        return False

    # Build the new message list: drop the compressed tool messages and insert
    # a single summary message in their place.
    #
    # The summary is emitted as a `role: "user"` message (NOT a `role: "tool"`
    # message) because a `tool` message must carry a `tool_call_id` that matches
    # a preceding assistant `tool_calls[].id`. A synthetic id like
    # "context-compression" has no such match, and strict OpenAI-compatible
    # providers reject the request with:
    #   "invalid params, tool result's tool id(context-compression) not found (2013)"
    # A `user` message has no such pairing requirement, so it is protocol-safe.
    new_messages: list[ChatCompletionRequestMessage] = []
    inserted = False
    for index, message in enumerate(request_messages):
        if index in keep_indices:
            new_messages.append(message)
            continue
        if index in compress_indices:
            if not inserted:
                new_messages.append(
                    ChatCompletionRequestMessage.model_validate(
                        {
                            "role": "user",
                            "content": (
                                "[Earlier tool results summarized to save context]\n\n"
                                + summary
                            ),
                        }
                    )
                )
                inserted = True
            continue
        new_messages.append(message)

    # Replace the list in place.
    request_messages[:] = new_messages
    logger.info(
        f"compressed {len(compress_indices)} older tool message(s) into a summary; "
        f"kept {len(keep_indices)} recent tool message(s)"
    )
    return True


def _format_tool_loop_stop_message(*, tool_turns_completed: int, max_tool_turns: int) -> str:
    return f"stopping tool loop after {tool_turns_completed} turn(s); max_tool_turns={max_tool_turns}"


def _normalize_tool_call_key(name: str, arguments: Any) -> str:
    """Build a stable comparison key for a tool call, ignoring whitespace.

    Used to detect when the model re-issues the same tool call across loop
    iterations (a "search loop") instead of converging on an answer.
    """
    arg_text = arguments if isinstance(arguments, str) else json.dumps(arguments, sort_keys=True, ensure_ascii=False)
    return f"{name}::{' '.join(arg_text.split())}"


def _detect_repeated_tool_calls(
    tool_call_items: list[tuple[str, Any]],
    seen_calls: dict[str, int],
    *,
    threshold: int = 3,
) -> bool:
    """Return True if any tool call in this iteration has already been issued
    ``threshold`` or more times across the loop.

    A weak model that keeps re-issuing the same search call without converging
    is a "search loop". Detecting it lets the bridge stop early and synthesize
    a final answer instead of burning tokens and context.

    The threshold is deliberately set above 2 so that a single re-run of a query
    during an otherwise productive research chain (e.g. re-searching a term in a
    different language, or re-running a query to confirm a result) does not kill
    the whole workflow. Only a call issued three or more times is treated as a
    genuine loop. Runaway loops are still bounded by the max-tool-turns and
    context-budget guards.
    """
    repeated = False
    for name, arguments in tool_call_items:
        key = _normalize_tool_call_key(name, arguments)
        seen_calls[key] = seen_calls.get(key, 0) + 1
        if seen_calls[key] >= threshold:
            repeated = True
    return repeated


def _extract_tool_message_text(message: ChatCompletionRequestMessage | Any) -> str | None:
    message_root = getattr(message, "root", message)
    if isinstance(message_root, dict):
        role_value = message_root.get("role")
        content = message_root.get("content")
    else:
        role_value = getattr(getattr(message_root, "role", None), "value", getattr(message_root, "role", None))
        content = getattr(message_root, "content", None)

    if role_value != "tool":
        return None

    if content is None:
        return None

    if hasattr(content, "root"):
        content = content.root

    if isinstance(content, list):
        text_chunks: list[str] = []
        for item in content:
            if isinstance(item, dict):
                text_value = item.get("text")
                if isinstance(text_value, str) and text_value:
                    text_chunks.append(text_value)
            elif hasattr(item, "text"):
                text_value = getattr(item, "text", None)
                if isinstance(text_value, str) and text_value:
                    text_chunks.append(text_value)
            elif hasattr(item, "root") and hasattr(item.root, "text"):
                text_value = getattr(item.root, "text", None)
                if isinstance(text_value, str) and text_value:
                    text_chunks.append(text_value)
        if text_chunks:
            return " ".join(text_chunks[:2])

    if isinstance(content, str):
        return content

    if isinstance(content, dict):
        text_value = content.get("text")
        if isinstance(text_value, str):
            return text_value

    return None


def _normalize_finish_reason(value: str | FinishReason1 | None) -> FinishReason1 | None:
    if value is None:
        return None

    if isinstance(value, FinishReason1):
        return value

    if not isinstance(value, str):
        return None

    normalized = value.strip().lower()
    mapping = {
        "stop": FinishReason1.stop,
        "length": FinishReason1.length,
        "tool_calls": FinishReason1.tool_calls,
        "content_filter": FinishReason1.content_filter,
        "function_call": FinishReason1.function_call,
    }
    return mapping.get(normalized)


def _build_tool_error_response(response: CreateChatCompletionResponse, tool_errors: list[str]) -> CreateChatCompletionResponse:
    error_summary = "; ".join(tool_errors)
    response.choices[0].message.content = (
        "I wasn't able to complete the request because one or more MCP tool calls failed: "
        + error_summary
    )
    response.choices[0].message.tool_calls = None
    response.choices[0].finish_reason = _normalize_finish_reason("stop") or FinishReason1.stop
    return response


def _is_recoverable_tool_error(error: str) -> bool:
    """Return True if a tool error is recoverable by feeding it back to the model.

    Validation errors (e.g. ``sequential-thinking`` rejecting malformed
    arguments) are recoverable — the model can correct its arguments and retry.
    Fatal errors (no client found, unknown tool) are not recoverable by the
    model, so the loop should stop rather than spin.
    """
    if not error:
        return False
    lowered = error.lower()
    fatal_markers = (
        "no mcp client found",
        "unknown tool",
        "tool not found",
        "client not found",
        "not found for tool",
    )
    if any(marker in lowered for marker in fatal_markers):
        return False
    return True


def _should_stop_tool_loop_on_tool_errors(
    tool_errors: list[str],
    request_messages: list[ChatCompletionRequestMessage],
) -> bool:
    if not tool_errors:
        return False

    # Fatal errors (no client / unknown tool) cannot be fixed by the model, so
    # stop immediately regardless of evidence.
    if any(not _is_recoverable_tool_error(error) for error in tool_errors):
        return True

    # Timeout errors with partial evidence are recoverable — the model can
    # continue with what it has. Keep looping even if there are several.
    evidence_text = "\n".join(
        _extract_tool_message_text(message) or ""
        for message in request_messages
        if getattr(getattr(message, "root", message), "role", None) == "tool"
    )
    timeout_error_count = sum(1 for error in tool_errors if "timeout" in error.lower() or "timed out" in error.lower())
    if timeout_error_count and evidence_text.strip():
        return False

    # Recoverable errors (validation, timeout) should be fed back to the model
    # for correction. Only stop if there are too many to avoid an infinite loop.
    if len(tool_errors) > 3:
        return True

    return False


def _build_synthesis_request(
    request: CreateChatCompletionRequest,
    *,
    stop_reason: str,
    request_messages: list[ChatCompletionRequestMessage],
    force_answer: bool = False,
) -> CreateChatCompletionRequest:
    synthesis_request = request.model_copy(deep=True)
    synthesis_request.messages = list(request_messages)
    synthesis_request.tools = []

    if force_answer:
        instruction = (
            "Write the final answer now. Do NOT call any tools and do NOT emit any tool-call "
            "markup. Use only the evidence already present in the conversation to produce a "
            "complete, well-structured answer to the original question. Be concise but thorough."
        )
    else:
        instruction = (
            "Synthesize the information gathered from the tool results into a helpful final answer. "
            "Use the evidence already present in the conversation, be concise but complete, and "
            "avoid mentioning the tool-loop limit unless it is necessary to explain missing information."
        )
    if stop_reason == "max_tool_turns":
        instruction += " The tool workflow stopped early, so if some information is incomplete, say so clearly."
    elif stop_reason == "max_context_tokens":
        instruction += " The tool workflow stopped early because the conversation context grew too large, so if some information is incomplete, say so clearly."
    elif stop_reason == "repeated_tool_calls":
        instruction += " The tool workflow stopped because the same tool call was repeated without new information, so synthesize the best answer from the evidence already gathered."
    elif stop_reason == "unfulfilled_action_stub":
        instruction += " A previous attempt only announced an action (e.g. \"Let me fetch...\") without completing it or calling any tool, so actually answer the question now using whatever information is already available."

    synthesis_request.messages.append(
        ChatCompletionRequestMessage.model_validate(
            {
                "role": "user",
                "content": instruction,
            }
        )
    )
    return synthesis_request


async def _try_synthesize_tool_loop_result(
    client: Any,
    request: CreateChatCompletionRequest,
    *,
    stop_reason: str,
    request_messages: list[ChatCompletionRequestMessage],
) -> CreateChatCompletionResponse | None:
    # First pass: ask the model to synthesize from the gathered evidence. If it
    # returns empty content or tries to call tools again (a common failure when
    # the history is full of tool calls), retry once with a stronger
    # "write the answer now, do not call tools" instruction.
    for attempt, force_answer in enumerate((False, True)):
        synthesis_request = _build_synthesis_request(
            request,
            stop_reason=stop_reason,
            request_messages=request_messages,
            force_answer=force_answer,
        )
        try:
            text = (
                await client.post(
                    "/chat/completions",
                    json=synthesis_request.model_dump(exclude_defaults=True, exclude_none=True, exclude_unset=True),
                )
            ).text
            response = CreateChatCompletionResponse.model_validate_json(text)
            content = getattr(response.choices[0].message, "content", None) if response.choices else None
            if content is None:
                if attempt == 0:
                    continue
                return None
            content_text = str(content)
            # If the synthesis contains pseudo tool-call markers, strip them and
            # keep any real analysis text around them. The synthesis request has no
            # tools, so markers are noise — but the model may have written a real
            # answer around them. Only reject if nothing usable remains.
            if _contains_pseudo_tool_call_markers(content_text):
                content_text = _strip_pseudo_tool_call_markers(content_text)
            if content_text.strip():
                response.choices[0].message.content = content_text
                response.choices[0].message.tool_calls = None
                response.choices[0].finish_reason = _normalize_finish_reason("stop") or FinishReason1.stop
                return response
            # Empty content: retry once with the stronger instruction.
            if attempt == 0:
                continue
        except Exception as exc:
            logger.warning(f"tool loop synthesis request failed: {exc}")
            if attempt == 0:
                continue

    return None


