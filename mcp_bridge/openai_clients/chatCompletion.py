# Memoization state for the model catalog. The catalog is read once and cached
# in-process, keyed by the file's mtime so a re-run of ``scripts/fetch_models.py``
# (which rewrites ``models.json``) is picked up without a process restart, while
# the hot path (``get_max_context_tokens`` inside the tool loop) never re-reads
# or re-parses the file on every iteration.
_model_catalog_cache: dict[str, int] | None = None
_model_catalog_mtime: float | None = None


def _load_model_catalog() -> dict[str, int]:
    """Load the local ``models.json`` catalog (if present) as a model_id -> context_length map.

    The catalog is generated by ``scripts/fetch_models.py`` from the provider's
    ``/models`` endpoint, so it reflects the real, current context windows
    (which often differ between a model's paid and ``:free`` variants). Returns
    an empty dict if the catalog is missing or unreadable.

    The result is memoized in-process and invalidated only when the file's
    mtime changes, so repeated calls (e.g. once per tool-loop iteration) are
    cheap and do not re-read the file from disk.
    """
    global _model_catalog_cache, _model_catalog_mtime

    catalog_path = os.getenv("MCP_BRIDGE_MODELS_CATALOG", "")
    if not catalog_path:
        catalog_path = os.path.join(os.path.dirname(__file__), "..", "..", "models.json")
    catalog_path = os.path.abspath(catalog_path)

    try:
        mtime = os.path.getmtime(catalog_path)
    except OSError:
        mtime = None

    if _model_catalog_cache is not None and mtime is not None and mtime == _model_catalog_mtime:
        return _model_catalog_cache

    try:
        with open(catalog_path, encoding="utf-8") as fh:
            document = json.load(fh)
        models = document.get("models", {})
        result: dict[str, int] = {}
        for mid, info in models.items():
            ctx = info.get("context_length") if isinstance(info, dict) else None
            if isinstance(ctx, int) and ctx > 0:
                result[mid] = ctx
    except Exception:
        result = {}

    _model_catalog_cache = result
    _model_catalog_mtime = mtime
    return result


def _infer_model_context_window(model_id: str | None) -> int:
    """Best-effort estimate of a model's context window (tokens).

    Resolution order:
      1. The local ``models.json`` catalog (generated from the provider's
         ``/models`` endpoint) — exact model ID match.
      2. Explicit ``model_context_windows`` config map (exact or suffix match).
      3. A context hint embedded in the model ID (e.g. ``128k``, ``1m``, ``200k``).
      4. A known-model lookup by a normalized prefix of the ID.
      5. ``DEFAULT_MODEL_CONTEXT_WINDOW``.
    """
    if not model_id:
        return DEFAULT_MODEL_CONTEXT_WINDOW

    # 1. Local models.json catalog (exact model ID).
    catalog = _load_model_catalog()
    if model_id in catalog:
        return catalog[model_id]

    # 2. Config map (exact match, then suffix match on the last path segment).
    try:
        from mcp_bridge.config import config

        configured = getattr(getattr(config, "inference_server", None), "model_context_windows", None)
        if isinstance(configured, dict):
            if model_id in configured:
                return int(configured[model_id])
            short = model_id.split("/")[-1]
            if short in configured:
                return int(configured[short])
    except Exception:
        pass

    # 3. Context hint embedded in the model ID.
    lowered = model_id.lower()
    # "1m" / "200k" style suffixes (e.g. "model-1m", "model-200k").
    m_match = re.search(r"(\d+)\s*m\b", lowered)
    if m_match:
        return int(m_match.group(1)) * 1_000_000
    k_match = re.search(r"(\d+)\s*(?:k|k\s*tokens?|tokens?)\b", lowered)
    if k_match:
        return int(k_match.group(1)) * 1000

    # 4. Known-model lookup by normalized prefix.
    normalized = re.sub(r"[:/]", "-", lowered).strip("-")
    for known, window in _KNOWN_MODEL_CONTEXT_WINDOWS.items():
        if known in normalized:
            return window

    return DEFAULT_MODEL_CONTEXT_WINDOW


def get_max_context_tokens(model_id: str | None = None) -> int:
    """Return the tool-loop context budget (tokens) for the given model.

    An explicit ``MCP_BRIDGE_MAX_CONTEXT_TOKENS`` environment variable always
    wins (it is a hard override). Otherwise the budget is derived from the
    model's context window scaled by ``MCP_BRIDGE_CONTEXT_BUDGET_FRACTION``
    (default 0.75), so different models get different budgets instead of a
    one-size-fits-all cap.
    """
    raw_value = os.getenv("MCP_BRIDGE_MAX_CONTEXT_TOKENS")
    if raw_value is not None:
        try:
            configured_value = int(raw_value)
        except ValueError:
            logger.warning(
                f"invalid MCP_BRIDGE_MAX_CONTEXT_TOKENS value: {raw_value}; using default {DEFAULT_MAX_CONTEXT_TOKENS}"
            )
            return DEFAULT_MAX_CONTEXT_TOKENS
        if configured_value < 1000:
            logger.warning(
                f"configured MCP_BRIDGE_MAX_CONTEXT_TOKENS={configured_value} is below the safe minimum 1000; using 1000"
            )
            return 1000
        return configured_value

    context_window = _infer_model_context_window(model_id)

    fraction_raw = os.getenv("MCP_BRIDGE_CONTEXT_BUDGET_FRACTION")
    try:
        fraction = float(fraction_raw) if fraction_raw is not None else DEFAULT_CONTEXT_BUDGET_FRACTION
    except ValueError:
        logger.warning(
            f"invalid MCP_BRIDGE_CONTEXT_BUDGET_FRACTION value: {fraction_raw}; using {DEFAULT_CONTEXT_BUDGET_FRACTION}"
        )
        fraction = DEFAULT_CONTEXT_BUDGET_FRACTION

    if not (0.1 <= fraction <= 1.0):
        logger.warning(
            f"MCP_BRIDGE_CONTEXT_BUDGET_FRACTION={fraction} out of range [0.1, 1.0]; using {DEFAULT_CONTEXT_BUDGET_FRACTION}"
        )
        fraction = DEFAULT_CONTEXT_BUDGET_FRACTION

    budget = int(context_window * fraction)
    return max(budget, 1000)


